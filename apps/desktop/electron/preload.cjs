const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('sufficeDesktop',{
  platform:process.platform,
  windowChrome:process.argv.find(arg=>/^--suffice-window-chrome=(windows|macos-native|macos-preview)$/.test(arg))?.split('=')[1]||'windows',
  browser:payload=>ipcRenderer.invoke('suffice:browser',payload),
  onBrowserState:callback=>{const listener=(_event,value)=>callback(value);ipcRenderer.on('suffice:browser-state',listener);return()=>ipcRenderer.removeListener('suffice:browser-state',listener);},
  deleteThread:id=>ipcRenderer.invoke('suffice:delete-thread',id),
  updateProject:payload=>ipcRenderer.invoke('suffice:update-project',payload),
  removeProject:folder=>ipcRenderer.invoke('suffice:remove-project',folder),
  fileOpenOptions:payload=>ipcRenderer.invoke('suffice:file-open-options',payload),
  openFileIn:payload=>ipcRenderer.invoke('suffice:file-open-in',payload),
  openProjectFolder:folder=>ipcRenderer.invoke('suffice:open-project-folder',folder),
  chooseProjectImage:()=>ipcRenderer.invoke('suffice:choose-project-image'),
  moveThread:payload=>ipcRenderer.invoke('suffice:move-thread',payload),
  viewStates:()=>ipcRenderer.invoke('suffice:view-states'),
  saveViewState:payload=>ipcRenderer.invoke('suffice:save-view-state',payload),
  refreshModels:()=>ipcRenderer.invoke('suffice:refresh-models'),
  resources:()=>ipcRenderer.invoke('suffice:resources'),
  resourceAction:payload=>ipcRenderer.invoke('suffice:resource-action',payload),
  approvalAnswer:payload=>ipcRenderer.invoke('suffice:approval-answer',payload),
  extensionAnswer:payload=>ipcRenderer.invoke('suffice:extension-answer',payload),
  providers:()=>ipcRenderer.invoke('suffice:providers'),
  providerLogin:payload=>ipcRenderer.invoke('suffice:provider-login',payload),
  providerAnswer:payload=>ipcRenderer.invoke('suffice:provider-answer',payload),
  providerCancel:()=>ipcRenderer.invoke('suffice:provider-cancel'),
  providerLogout:id=>ipcRenderer.invoke('suffice:provider-logout',id),
  desktopPreference:payload=>ipcRenderer.invoke('suffice:desktop-preference',payload),
  settingsAction:action=>ipcRenderer.invoke('suffice:settings-action',action),
  onClearCache:callback=>{ipcRenderer.on('suffice:clear-cache',callback);return()=>ipcRenderer.removeListener('suffice:clear-cache',callback);},
  onNotification:callback=>{const listener=(_e,value)=>callback(value);ipcRenderer.on('suffice:notification',listener);return()=>ipcRenderer.removeListener('suffice:notification',listener);},
  preferences:()=>ipcRenderer.invoke('suffice:preferences'),
  onProviderAuth:callback=>{const listener=(_event,value)=>callback(value);ipcRenderer.on('suffice:provider-auth',listener);return()=>ipcRenderer.removeListener('suffice:provider-auth',listener);},
  terminalCreate:payload=>ipcRenderer.invoke('suffice:terminal-create',payload),
  terminalWrite:payload=>ipcRenderer.invoke('suffice:terminal-write',payload),
  terminalResize:payload=>ipcRenderer.invoke('suffice:terminal-resize',payload),
  terminalClose:payload=>ipcRenderer.invoke('suffice:terminal-close',payload),
  onTerminalEvent:callback=>{const listener=(_event,value)=>callback(value);ipcRenderer.on('suffice:terminal-event',listener);return()=>ipcRenderer.removeListener('suffice:terminal-event',listener);},
  openExternal:url=>ipcRenderer.invoke('suffice:open-external',url),
  windowControl:action=>ipcRenderer.invoke('suffice:window',action),
  usage:threadId=>ipcRenderer.invoke('suffice:usage',threadId),
  files:directory=>ipcRenderer.invoke('suffice:files',directory),
  file:name=>ipcRenderer.invoke('suffice:file',name),
  changes:()=>ipcRenderer.invoke('suffice:changes'),
  diff:name=>ipcRenderer.invoke('suffice:diff',name),
  status:()=>ipcRenderer.invoke('suffice:status'),
  models:options=>ipcRenderer.invoke('suffice:models',options),
  forkThread:id=>ipcRenderer.invoke('suffice:fork-thread',id),
  threads:()=>ipcRenderer.invoke('suffice:threads'),
  openThread:id=>ipcRenderer.invoke('suffice:thread',id),
  initialProject:()=>ipcRenderer.invoke('suffice:initial-project'),
  chooseProject:()=>ipcRenderer.invoke('suffice:project'),
  branches:()=>ipcRenderer.invoke('suffice:branches'),
  selectBranch:payload=>ipcRenderer.invoke('suffice:select-branch',payload),
  projects:()=>ipcRenderer.invoke('suffice:projects'),
  selectProject:(id,options)=>ipcRenderer.invoke('suffice:select-project',id,options),
  run:payload=>ipcRenderer.invoke('suffice:run',payload),
  runBackground:payload=>ipcRenderer.invoke('suffice:run-background',payload),
  clipboardFiles:()=>ipcRenderer.invoke('suffice:clipboard-files'),
  abort:threadId=>ipcRenderer.invoke('suffice:abort',threadId),
  steer:payload=>ipcRenderer.invoke('suffice:steer',payload),
  reset:()=>ipcRenderer.invoke('suffice:reset'),
  onEvent:callback=>{const listener=(_event,value)=>callback(value);ipcRenderer.on('suffice:event',listener);return()=>ipcRenderer.removeListener('suffice:event',listener);},
});
