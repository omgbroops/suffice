const {contextBridge,ipcRenderer}=require('electron');
// Electron prefixes main-process errors with "Error invoking remote method 'x': Error: "; users only need the message.
const invoke=(channel,...args)=>ipcRenderer.invoke(channel,...args).catch(error=>{throw new Error(String(error?.message||error).replace(/^Error invoking remote method '[^']*': (?:\w*Error: )?/,''));});
contextBridge.exposeInMainWorld('sufficeDesktop',{
  windowControl:action=>invoke('suffice:window',action),
  usage:()=>invoke('suffice:usage'),
  files:directory=>invoke('suffice:files',directory),
  file:name=>invoke('suffice:file',name),
  changes:()=>invoke('suffice:changes'),
  diff:name=>invoke('suffice:diff',name),
  status:()=>invoke('suffice:status'),
  models:()=>invoke('suffice:models'),
  threads:()=>invoke('suffice:threads'),
  gitInfo:()=>invoke('suffice:git-info'),
  issues:()=>invoke('suffice:issues'),
  prs:()=>invoke('suffice:prs'),
  openGithub:url=>invoke('suffice:open-github',url),
  openThread:id=>invoke('suffice:thread',id),
  chooseProject:()=>invoke('suffice:project'),
  projects:()=>invoke('suffice:projects'),
  selectProject:id=>invoke('suffice:select-project',id),
  run:payload=>invoke('suffice:run',payload),
  runBackground:payload=>invoke('suffice:run-background',payload),
  clipboardFiles:()=>invoke('suffice:clipboard-files'),
  abort:()=>invoke('suffice:abort'),
  login:()=>invoke('suffice:login'),
  logout:()=>invoke('suffice:logout'),
  loginInput:text=>invoke('suffice:login-input',text),
  loginCancel:()=>invoke('suffice:login-cancel'),
  loginOpen:()=>invoke('suffice:login-open'),
  reset:()=>invoke('suffice:reset'),
  onEvent:callback=>{const listener=(_event,value)=>callback(value);ipcRenderer.on('suffice:event',listener);return()=>ipcRenderer.removeListener('suffice:event',listener);},
});
